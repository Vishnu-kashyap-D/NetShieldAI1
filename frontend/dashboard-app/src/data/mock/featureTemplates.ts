/**
 * Builds one realistic feature vector for a given attack category: starts from that
 * category's real-shaped template and applies small per-sample jitter to continuous
 * features, so repeated alerts of the same category don't all carry identical values.
 */
export function buildFeatureVector(rng: ReturnType<typeof createRng>, category: AttackCategory): FeatureVector {
  const template = CATEGORY_FEATURE_TEMPLATES[category];
  const vector: FeatureVector = {};
  for (const name of FEATURE_NAMES) {
    const value = template[name] ?? 0;
    if (value === null || DISCRETE_FEATURES.has(name)) {
      vector[name] = value;
    } else {
      vector[name] = Math.round(jitter(rng, value, 0.22) * 1000) / 1000;
    }
  }
  return vector;
}
